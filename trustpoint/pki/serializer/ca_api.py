"""Public request and response contracts for CA and CRL management."""

from typing import Any, ClassVar

from rest_framework import serializers

from pki.models import CaModel, CertificateModel, CrlModel
from pki.models.ca_rollover import CaRolloverModel
from pki.serializer.issuing_ca import IssuingCaSerializer
from pki.serializer.owner_credential import CertificateIssuanceContentSerializer


class CaSerializer(IssuingCaSerializer):
    """CA inventory, hierarchy, and public configuration; never private key material."""

    certificate = serializers.SerializerMethodField()
    next_crl_generation_scheduled_at = serializers.DateTimeField(read_only=True, allow_null=True)

    def get_certificate(self, obj: CaModel) -> int | None:
        """Return the public certificate ID for both keyless and credential-backed CAs."""
        certificate = obj.ca_certificate_model
        return certificate.pk if certificate is not None else None

    class Meta(IssuingCaSerializer.Meta):
        """Include settings needed to manage an existing CA."""

        fields: ClassVar[list[str]] = [
            *IssuingCaSerializer.Meta.fields,
            'parent_ca',
            'certificate',
            'chain_truststore',
            'remote_host',
            'remote_port',
            'remote_path',
            'est_username',
            'crl_cycle_enabled',
            'crl_cycle_interval_hours',
            'crl_validity_hours',
            'auto_crl_on_revocation_enabled',
            'next_crl_generation_scheduled_at',
        ]
        read_only_fields = fields


class CaCertificateSerializer(serializers.ModelSerializer[CertificateModel]):
    """Public certificate information for CA inventories."""

    class Meta:
        """Expose certificate contents without the associated private key."""

        model = CertificateModel
        fields = ('id', 'common_name', 'serial_number', 'not_valid_before', 'not_valid_after', 'cert_pem')
        read_only_fields = fields


class CrlSerializer(serializers.ModelSerializer[CrlModel]):
    """CRL metadata and contents."""

    revoked_serial_numbers = serializers.SerializerMethodField()
    issuer = serializers.SerializerMethodField()
    revoked_certificates = serializers.SerializerMethodField()

    class Meta:
        """CRLs are immutable after import or generation."""

        model = CrlModel
        fields = (
            'id',
            'ca',
            'crl_number',
            'this_update',
            'next_update',
            'is_active',
            'created_at',
            'updated_at',
            'crl_pem',
            'revoked_serial_numbers',
            'issuer',
            'revoked_certificates',
        )
        read_only_fields = fields

    def get_revoked_serial_numbers(self, obj: CrlModel) -> list[str]:
        """Use hexadecimal strings so large certificate serials remain lossless in JSON."""
        return [f'{number:X}' for number in sorted(obj.get_revoked_serial_numbers())]

    def get_issuer(self, obj: CrlModel) -> str:
        """Return the CRL issuer distinguished name."""
        return obj.get_crl_as_crypto().issuer.rfc4514_string()

    def get_revoked_certificates(self, obj: CrlModel) -> list[dict[str, str | None]]:
        """Expose revocation timestamps and reasons without losing large serial numbers."""
        from cryptography import x509  # noqa: PLC0415

        entries = []
        for revoked in obj.get_crl_as_crypto():
            try:
                reason = revoked.extensions.get_extension_for_class(x509.CRLReason).value.reason.name
            except x509.ExtensionNotFound:
                reason = None
            entries.append(
                {
                    'serial_number': f'{revoked.serial_number:X}',
                    'revocation_date': revoked.revocation_date_utc.isoformat(),
                    'reason': reason,
                }
            )
        return entries


class CrlImportSerializer(serializers.Serializer[Any]):
    """Import a PEM or DER CRL, optionally checking it against an issuing CA."""

    crl_file = serializers.FileField(write_only=True)
    ca = serializers.PrimaryKeyRelatedField(queryset=CaModel.objects.all(), required=False, allow_null=True)
    set_active = serializers.BooleanField(default=True)


class CaGenerateSerializer(serializers.Serializer[Any]):
    """Select a backend-supported key type for the autogenerated PKI."""

    key_type = serializers.CharField()


class CaPkcs12Serializer(serializers.Serializer[Any]):
    """Import a CA credential from a PKCS#12 file."""

    unique_name = serializers.CharField(required=False, allow_blank=True, default='')
    pkcs12_file = serializers.FileField(write_only=True)
    pkcs12_password = serializers.CharField(required=False, allow_blank=True, write_only=True, default='')


class CaRemoteSerializer(serializers.Serializer[Any]):
    """Configure an upstream CA or registration authority."""

    unique_name = serializers.CharField(max_length=256)
    key_type = serializers.CharField()
    remote_host = serializers.CharField()
    remote_port = serializers.IntegerField(min_value=1, max_value=65535)
    remote_path = serializers.CharField()
    est_username = serializers.CharField(required=False, allow_blank=True)
    est_password = serializers.CharField(required=False, allow_blank=True, write_only=True, trim_whitespace=False)
    cmp_shared_secret = serializers.CharField(required=False, allow_blank=True, write_only=True, trim_whitespace=False)
    is_ra_mode = serializers.BooleanField(default=False)


class CaExternalCsrSerializer(serializers.Serializer[Any]):
    """Create a managed key for an externally signed CA certificate."""

    unique_name = serializers.CharField(max_length=256)
    key_type = serializers.CharField()


class CaTruststoreSerializer(serializers.Serializer[Any]):
    """Associate a truststore after validating its intended usage."""

    trust_store = serializers.IntegerField(min_value=1)


class CaCrlSettingsSerializer(serializers.Serializer[Any]):
    """Partial CRL configuration; existing values fill omitted fields."""

    crl_cycle_enabled = serializers.BooleanField(required=False)
    crl_cycle_interval_hours = serializers.FloatField(required=False, min_value=5 / 60)
    crl_validity_hours = serializers.FloatField(required=False, min_value=1)
    auto_crl_on_revocation_enabled = serializers.BooleanField(required=False)


class CaRolloverSerializer(serializers.ModelSerializer[CaRolloverModel]):
    """Rollover state and history."""

    class Meta:
        """State transitions are only available through dedicated actions."""

        model = CaRolloverModel
        fields = (
            'id',
            'old_issuing_ca',
            'new_issuing_ca',
            'state',
            'strategy_type',
            'planned_at',
            'started_at',
            'completed_at',
            'transition_scheduled_at',
            'initiated_by',
            'notes',
        )
        read_only_fields = fields


class CaRolloverPlanSerializer(serializers.Serializer[Any]):
    """Acquire replacement credentials using the same methods as the UI."""

    old_issuing_ca = serializers.PrimaryKeyRelatedField(queryset=CaModel.objects.all())
    method = serializers.ChoiceField(choices=['pkcs12', 'separate_files', 'est', 'cmp'])
    unique_name = serializers.CharField(required=False, allow_blank=True)
    pkcs12_file = serializers.FileField(required=False, write_only=True)
    pkcs12_password = serializers.CharField(required=False, allow_blank=True, write_only=True)
    private_key_file = serializers.FileField(required=False, write_only=True)
    private_key_file_password = serializers.CharField(required=False, allow_blank=True, write_only=True)
    ca_certificate = serializers.FileField(required=False, write_only=True)
    ca_certificate_chain = serializers.FileField(required=False, write_only=True)
    key_type = serializers.CharField(required=False)
    remote_host = serializers.CharField(required=False)
    remote_port = serializers.IntegerField(required=False, min_value=1, max_value=65535)
    remote_path = serializers.CharField(required=False)
    est_username = serializers.CharField(required=False, allow_blank=True)
    est_password = serializers.CharField(required=False, allow_blank=True, write_only=True)
    cmp_shared_secret = serializers.CharField(required=False, allow_blank=True, write_only=True)
    transition_scheduled_at = serializers.DateTimeField(required=False)
    notes = serializers.CharField(required=False, allow_blank=True)


class EncodingSerializer(serializers.Serializer[Any]):
    """Download encoding, deliberately avoiding DRF's reserved format parameter."""

    encoding = serializers.ChoiceField(choices=['pem', 'der'], default='pem')


class CaCertificateUploadSerializer(serializers.Serializer[Any]):
    """Attach the CA certificate issued for a pending managed key."""

    certificate = serializers.FileField(write_only=True)


class CaEnrollmentSerializer(CertificateIssuanceContentSerializer):
    """Certificate profile content with optional CMP sender identifier."""

    sender_kid = serializers.IntegerField(required=False, min_value=0)
