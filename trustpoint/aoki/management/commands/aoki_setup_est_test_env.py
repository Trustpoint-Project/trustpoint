"""Sets up a Trustpoint test environment for AOKI DevOwnerID EST enrollment testing.

This command re-uses the certificates generated by ``aoki_gen_test_certs`` and creates:
- A local issuing CA called ``DevOwnerIDCA`` (root + intermediate, RSA-2048).
- A domain ``DevOwnerIDDomain`` associated with that CA.
- A device ``DevOwnerIDDevice`` in that domain, configured for EST username/password
  no-onboarding with password ``devownerid123``.
- A TLS truststore ``DevOwnerIDTLSTruststore`` containing the Trustpoint HTTPS server cert.
- An ``OwnerCredentialModel`` (``DevOwnerIDOwnerCred``) configured for remote EST enrollment
  via localhost:443, path /.well-known/est/DevOwnerIDDomain/dev_owner_id/simpleenroll,
  key type RSA-2048, linked to the TLS truststore above.
"""

from __future__ import annotations

from pathlib import Path
from typing import TYPE_CHECKING

from django.core.management import call_command
from django.core.management.base import BaseCommand

from aoki.management.setup_helpers import EstTestEnvironmentMixin
from devices.models import DeviceModel
from onboarding.models import NoOnboardingConfigModel, NoOnboardingPkiProtocol
from pki.models.credential import OwnerCredentialModel

if TYPE_CHECKING:
    from typing import Any

    from pki.models import DomainModel
    from pki.models.truststore import TruststoreModel

CA_UNIQUE_NAME = 'DevOwnerIDCA'
DOMAIN_UNIQUE_NAME = 'DevOwnerIDDomain'
DEVICE_COMMON_NAME = 'DevOwnerIDDevice'
DEVICE_SERIAL_NUMBER = 'DEVOWNERID-EST-001'
EST_PASSWORD = 'devownerid123'  # noqa: S105  # fixed credential for the local DevOwnerID test environment

OWNER_CRED_UNIQUE_NAME = 'DevOwnerIDOwnerCred'
TRUSTSTORE_UNIQUE_NAME = 'DevOwnerIDTLSTruststore'
HTTPS_SERVER_CERT_PATH = (
    Path(__file__).resolve().parents[4] / 'tests' / 'data' / 'x509' / 'https_server.crt'
)

REMOTE_HOST = 'localhost'
REMOTE_PORT = 443
REMOTE_PATH = f'/.well-known/est/{DOMAIN_UNIQUE_NAME}/dev_owner_id/simpleenroll'
KEY_TYPE = 'RSA-2048'


class Command(EstTestEnvironmentMixin, BaseCommand):
    """Creates a Trustpoint test environment for AOKI DevOwnerID EST enrollment testing."""

    help = (
        'Creates a local issuing CA ("DevOwnerIDCA"), domain ("DevOwnerIDDomain"), '
        'and device ("DevOwnerIDDevice") for AOKI DevOwnerID EST enrollment testing.'
    )

    ca_unique_name = CA_UNIQUE_NAME
    domain_unique_name = DOMAIN_UNIQUE_NAME
    truststore_unique_name = TRUSTSTORE_UNIQUE_NAME
    https_server_cert_path = HTTPS_SERVER_CERT_PATH

    def handle(self, *args: Any, **kwargs: Any) -> None:
        """Execute the command.

        :param args: Additional positional arguments (unused).
        :param kwargs: Additional keyword arguments (unused).
        """
        del args, kwargs  # Unused

        # Ensure certificate profiles exist before creating any domain / device.
        call_command('create_default_cert_profiles')

        issuing_ca = self._get_or_create_issuing_ca()
        domain = self._get_or_create_domain(issuing_ca)
        self._get_or_create_device(domain)
        truststore = self._get_or_create_tls_truststore()
        self._get_or_create_owner_credential(truststore)

        self.log_and_stdout('\n=== AOKI EST test environment ready ===')
        self.log_and_stdout(f'  CA:           {CA_UNIQUE_NAME}')
        self.log_and_stdout(f'  Domain:       {DOMAIN_UNIQUE_NAME}')
        self.log_and_stdout(f'  Device:       {DEVICE_COMMON_NAME}  (EST password: [redacted])')
        self.log_and_stdout(f'  Truststore:   {TRUSTSTORE_UNIQUE_NAME}')
        self.log_and_stdout(f'  OwnerCred:    {OWNER_CRED_UNIQUE_NAME}')
        self.log_and_stdout(f'    host:       {REMOTE_HOST}:{REMOTE_PORT}')
        self.log_and_stdout(f'    path:       {REMOTE_PATH}')
        self.log_and_stdout(f'    key type:   {KEY_TYPE}')
        self.log_and_stdout(f'    username:   {DEVICE_COMMON_NAME}')
        self.log_and_stdout('    password:   [redacted]')

    # ------------------------------------------------------------------
    # Private helpers
    # ------------------------------------------------------------------


    def _get_or_create_device(self, domain: DomainModel) -> DeviceModel:
        """Return an existing device or create ``DevOwnerIDDevice`` in *domain*.

        The device is configured for EST username/password no-onboarding with
        password ``devownerid123``.

        :param domain: The domain to place the device in.
        :returns: The :class:`~devices.models.DeviceModel` for ``DevOwnerIDDevice``.
        """
        if DeviceModel.objects.filter(common_name=DEVICE_COMMON_NAME).exists():
            self.log_and_stdout(f'Device "{DEVICE_COMMON_NAME}" already exists, skipping creation.')
            return DeviceModel.objects.get(common_name=DEVICE_COMMON_NAME)

        no_onboarding_config = NoOnboardingConfigModel()
        no_onboarding_config.set_pki_protocols([NoOnboardingPkiProtocol.EST_USERNAME_PASSWORD])
        no_onboarding_config.est_password = EST_PASSWORD
        no_onboarding_config.full_clean()
        no_onboarding_config.save()

        device = DeviceModel(
            common_name=DEVICE_COMMON_NAME,
            serial_number=DEVICE_SERIAL_NUMBER,
            domain=domain,
            device_type=DeviceModel.DeviceType.GENERIC_DEVICE,
            no_onboarding_config=no_onboarding_config,
        )
        device.full_clean()
        device.save()
        self.log_and_stdout(f'Created device "{DEVICE_COMMON_NAME}".')
        return device


    def _get_or_create_owner_credential(self, truststore: TruststoreModel) -> OwnerCredentialModel:
        """Return an existing OwnerCredential or create one configured for remote EST enrollment.

        The credential is configured to enroll via::

            https://localhost:443/.well-known/est/DevOwnerIDDomain/dev_owner_id/simpleenroll

        using EST username/password (username = device common name, password = EST password)
        and RSA-2048 key pairs.  The provided *truststore* is used to verify the TLS
        connection to the remote EST server.

        :param truststore: The TLS truststore to use for verifying the EST server.
        :returns: The :class:`~pki.models.credential.OwnerCredentialModel` for
            ``DevOwnerIDOwnerCred``.
        """
        if OwnerCredentialModel.objects.filter(unique_name=OWNER_CRED_UNIQUE_NAME).exists():
            self.log_and_stdout(f'OwnerCredential "{OWNER_CRED_UNIQUE_NAME}" already exists, skipping creation.')
            return OwnerCredentialModel.objects.get(unique_name=OWNER_CRED_UNIQUE_NAME)

        no_onboarding_config = NoOnboardingConfigModel()
        no_onboarding_config.set_pki_protocols([NoOnboardingPkiProtocol.EST_USERNAME_PASSWORD])
        no_onboarding_config.est_password = EST_PASSWORD
        no_onboarding_config.trust_store = truststore
        no_onboarding_config.full_clean()
        no_onboarding_config.save()

        owner_cred = OwnerCredentialModel(
            unique_name=OWNER_CRED_UNIQUE_NAME,
            owner_credential_type=OwnerCredentialModel.OwnerCredentialTypeChoice.REMOTE_EST,
            remote_host=REMOTE_HOST,
            remote_port=REMOTE_PORT,
            remote_path=REMOTE_PATH,
            est_username=DEVICE_COMMON_NAME,
            key_type=KEY_TYPE,
            no_onboarding_config=no_onboarding_config,
        )
        owner_cred.full_clean()
        owner_cred.save()
        self.log_and_stdout(f'Created OwnerCredential "{OWNER_CRED_UNIQUE_NAME}".')
        return owner_cred
